package task3.population;

/**
 * Зберігає демографічні показники країни для подальшої обробки.
 */
public interface Population {

    /**
     * Реалізує користувацьке визначення населення країни.
     */
    void setPopulation();

    /**
     * Визначає населення країни за аргументом.
     */
    void setPopulation(int population);

    /**
     * Повертає населення країни.
     */
    int getPopulation();

    /**
     * Реалізує користувацьке визначення народжуваності країни.
     */
    void setNatality();

    /**
     * Визначає народжуваність країни за аргументом.
     */
    void setNatality(int natality);

    /**
     * Повертає народжуваність країни.
     */
    int getNatality();

    /**
     * Реалізує користувацьке визначення смертності країни.
     */
    void setMortality();

    /**
     * Визначає смертність країни за аргументом.
     */
    void setMortality(int mortality);

    /**
     * Повертає смертність країни.
     */
    int getMortality();

    /**
     * Розраховує населення країни
     * при користувацькому введенні терміна розрахунку.
     */
    int calculatePopulation();

    /**
     * Розраховує населення країни
     * при отриманні терміна розрахунку за аргументом.
     */
    int calculatePopulation(int years);

    /**
     * Виводить розраховане населення країни
     * при користувацькому введенні терміна розрахунку.
     */
    void printCalculatedPopulation();

    /**
     * Виводить розраховане населення країни
     * при отриманні терміна розрахунку за аргументом.
     */
    void printCalculatedPopulation(int years);
}